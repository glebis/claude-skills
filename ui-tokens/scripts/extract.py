#!/usr/bin/env python3
"""Extract design tokens from a product's CSS (and HTML <style>/<link>) into tokens.json and tokens.ts.

usage: extract.py OUT_DIR FILE [FILE ...]
  FILE: .css or .html. Custom properties in :root are the light theme, [data-theme="dark"] (or a
  prefers-color-scheme: dark block) the dark one. Also collected: font families (CSS vars + Google
  Fonts links), every transition/animation/@keyframes with its selector, px values used for
  padding/margin/gap (the spacing scale, by frequency) and border-radius values.
"""
import json, re, sys
from collections import Counter
from pathlib import Path

HEX = re.compile(r"#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|hsla?\([^)]*\)")

def css_of(path: Path) -> str:
    t = path.read_text(errors="ignore")
    if path.suffix.lower() in (".html", ".htm"):
        return "\n".join(re.findall(r"<style[^>]*>(.*?)</style>", t, re.S))
    return t

def blocks(css: str):
    """Yield (selector, body) for flat rules, descending one level into @media."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    i, n = 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0: break
        sel = css[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            depth += {"{": 1, "}": -1}.get(css[k], 0); k += 1
        body = css[j + 1:k - 1]
        if sel.startswith("@media") or sel.startswith("@supports"):
            for s, b in blocks(body):
                yield (sel + " " + s, b)
        else:
            yield sel, body
        i = k

def decls(body: str):
    for d in body.split(";"):
        if ":" in d:
            p, v = d.split(":", 1)
            yield p.strip(), v.strip()

def kind(name: str, val: str) -> str:
    if name.startswith("--f-"): return "font"
    if HEX.fullmatch(val.strip()): return "color"
    if name.startswith("--t-"): return "size"
    if re.match(r"--r(-|$)", name): return "radius"
    if name.startswith("--h-"): return "height"
    if "shadow" in name: return "shadow"
    if HEX.fullmatch(val.strip()): return "color"
    return "other"

def main():
    out = Path(sys.argv[1]); files = [Path(p) for p in sys.argv[2:]]
    out.mkdir(parents=True, exist_ok=True)
    light, dark = {}, {}
    motion, keyframes, spacing, radii, fams = [], {}, Counter(), Counter(), []
    for f in files:
        raw = f.read_text(errors="ignore")
        for fam in re.findall(r"fonts\.googleapis\.com/css2\?([^\"'>]+)", raw):
            fams += [re.sub(r"[:&].*", "", x).replace("+", " ") for x in fam.split("family=")[1:]]
        for sel, body in blocks(css_of(f)):
            is_dark = "dark" in sel
            if sel.endswith(":root") or ":root[" in sel or sel == ":root":
                tgt = dark if is_dark else light
                for p, v in decls(body):
                    if p.startswith("--"): tgt[p] = v
            if sel.startswith("@keyframes"):
                keyframes[sel.split()[1]] = {"file": f.name, "body": " ".join(body.split())}
                continue
            for p, v in decls(body):
                if p in ("transition", "animation", "transition-duration", "animation-name") and v != "none":
                    motion.append({"selector": sel[:80], "property": p, "value": v, "file": f.name})
                if p in ("padding", "margin", "gap", "row-gap", "column-gap", "padding-block", "padding-inline", "margin-block", "margin-inline"):
                    spacing.update(int(x) for x in re.findall(r"(?<![\w.])(\d+)px", v) if int(x) > 0)
                if p == "border-radius":
                    radii.update(re.findall(r"\d+px|var\(--r[\w-]*\)", v))
    group = lambda d: {k: {n: v for n, v in d.items() if kind(n, v) == k} for k in ("color", "font", "size", "radius", "height", "shadow", "other")}
    durations = Counter()
    for m in motion:
        for d in re.findall(r"(\d*\.?\d+)(ms|s)\b", m["value"]):
            durations[round(float(d[0]) * (1 if d[1] == "ms" else 1000))] += 1
    tokens = {
        "source": [str(f) for f in files],
        "light": group(light), "dark": group(dark),
        "fontFamilies": sorted(set(fams)),
        "spacingPx": [v for v, _ in sorted(spacing.most_common(12))],
        "spacingFrequency": dict(spacing.most_common(12)),
        "radiusUse": dict(radii.most_common(10)),
        "motion": {"transitions": motion, "keyframes": keyframes,
                   "durationsMs": dict(sorted(durations.items())),
                   "note": "UI motion in the product itself; the video may exaggerate it but keeps its order and feel"},
    }
    (out / "tokens.json").write_text(json.dumps(tokens, indent=2, ensure_ascii=False))
    # tokens.ts: the flat light palette + fonts + radii for raea components
    flat = lambda d: {k.lstrip("-").replace("-", "_"): v for k, v in d.items()}
    ts = ["// generated by ui-tokens/extract.py from " + ", ".join(f.name for f in files) + " — do not edit",
          "export const T = " + json.dumps(flat(light), indent=1) + " as const;",
          "export const DARK = " + json.dumps(flat(dark), indent=1) + " as const;",
          "export const MOTION_MS = " + json.dumps(dict(sorted(durations.items()))) + ";"]
    (out / "tokens.ts").write_text("\n".join(ts) + "\n")
    print(f"{out/'tokens.json'}: {len(light)} light vars, {len(dark)} dark, {len(motion)} transitions, "
          f"{len(keyframes)} keyframes, fonts {tokens['fontFamilies']}, spacing {tokens['spacingPx']}")

if __name__ == "__main__":
    main()
